"""Generate SVG path data for the intro signature.

Turns "Rohith Pinnamaneni" set in a signature font into SVG paths and
writes components/intro/signature-data.ts. Each contour is rotated so it
starts at its left-most point, which makes the animated reveal travel
left to right like a pen.

    python scripts/signature.py            # default font + text
    python scripts/signature.py "Some Name" path/to/Font.ttf

Font: Mrs Saint Delafield (SIL Open Font License, see OFL-MrsSaintDelafield.txt).
"""

import json
import os
import sys

from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
TEXT = sys.argv[1] if len(sys.argv) > 1 else "Rohith Pinnamaneni"
FONT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "MrsSaintDelafield-Regular.ttf")
OUT = os.path.join(HERE, "..", "components", "intro", "signature-data.ts")
PAD = 40


def fmt(v):
    s = f"{v:.1f}"
    return s[:-2] if s.endswith(".0") else s


def contours_of(glyph_set, name):
    pen = RecordingPen()
    glyph_set[name].draw(pen)
    contours, cur = [], None
    for op, args in pen.value:
        if op == "moveTo":
            cur = {"start": args[0], "segs": []}
        elif op in ("lineTo", "curveTo", "qCurveTo"):
            if cur is None:  # contour made only of off-curve points: no moveTo
                cur = {"start": None, "segs": []}
            cur["segs"].append((op, list(args)))
        elif op in ("closePath", "endPath"):
            if cur and cur["segs"]:
                contours.append(cur)
            cur = None
    return contours


def to_cubic_segments(c):
    """Return [(start, op, points)] with qCurveTo split into single quads."""
    mid = lambda a, b: ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
    if c["start"] is None:
        offs = [q for q in c["segs"][0][1] if q is not None]
        start = mid(offs[-1], offs[0])
        out, p = [], start
        for i, off in enumerate(offs):
            nxt = mid(off, offs[(i + 1) % len(offs)])
            out.append((p, "Q", [off, nxt]))
            p = nxt
        return out
    out, p = [], c["start"]
    for op, pts in c["segs"]:
        if op == "qCurveTo":
            # TrueType implied on-curve points between consecutive off-curve points
            offs, end = pts[:-1], pts[-1]
            if end is None:  # closed all-off-curve contour (rare)
                end = ((offs[-1][0] + offs[0][0]) / 2, (offs[-1][1] + offs[0][1]) / 2)
            for i, off in enumerate(offs):
                nxt = end if i == len(offs) - 1 else ((off[0] + offs[i + 1][0]) / 2, (off[1] + offs[i + 1][1]) / 2)
                out.append((p, "Q", [off, nxt]))
                p = nxt
        elif op == "curveTo":
            out.append((p, "C", pts))
            p = pts[-1]
        else:
            out.append((p, "L", pts))
            p = pts[-1]
    if p != c["start"]:
        out.append((p, "L", [c["start"]]))
    return out


def path_d(segs, tx, ty):
    X = lambda pt: fmt(pt[0] + tx)
    Y = lambda pt: fmt(ty - pt[1])
    d = [f"M{X(segs[0][0])} {Y(segs[0][0])}"]
    for _, op, pts in segs:
        d.append(op + " ".join(f"{X(q)} {Y(q)}" for q in pts))
    return "".join(d) + "Z"


def main():
    font = TTFont(FONT)
    cmap = font.getBestCmap()
    gs = font.getGlyphSet()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    asc = font["hhea"].ascent

    x = 0.0
    glyphs = []
    minx = miny = 1e9
    maxx = maxy = -1e9
    for ch in TEXT:
        name = cmap[ord(ch)]
        adv = hmtx[name][0]
        cs = contours_of(gs, name)
        segs_list = []
        for c in cs:
            segs = to_cubic_segments(c)
            # rotate to start at the left-most on-curve point
            k = min(range(len(segs)), key=lambda i: segs[i][0][0])
            segs = segs[k:] + segs[:k]
            segs_list.append(segs)
            for s in segs:
                for pt in [s[0]] + s[2]:
                    minx, maxx = min(minx, pt[0] + x), max(maxx, pt[0] + x)
                    miny, maxy = min(miny, asc - pt[1]), max(maxy, asc - pt[1])
        if segs_list:
            glyphs.append((ch, x, segs_list))
        x += adv

    tx0, ty0 = -minx + PAD, asc - miny + PAD
    width, height = maxx - minx + 2 * PAD, maxy - miny + 2 * PAD
    data = []
    for ch, gx, segs_list in glyphs:
        contours = [path_d(s, gx + tx0, ty0) for s in segs_list]
        data.append({"char": ch, "contours": contours})

    ts = (
        "/* Generated by scripts/signature.py — do not edit by hand.\n"
        f"   Text: {TEXT!r} · Font: {os.path.basename(FONT)} (SIL OFL) */\n\n"
        f"export const SIGNATURE_VIEWBOX = {json.dumps([0, 0, round(width), round(height)])} as const;\n"
        f"export const SIGNATURE_UPM = {upm};\n\n"
        "export const SIGNATURE_GLYPHS: { char: string; contours: string[] }[] = "
        + json.dumps(data, ensure_ascii=False, indent=1)
        + ";\n"
    )
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(ts)
    print(f"wrote {os.path.normpath(OUT)} — {len(data)} glyphs, viewBox {round(width)}x{round(height)}, {len(ts)//1024} KB")


if __name__ == "__main__":
    main()
